// Склоняем только слово кириллицей с заглавной или строчной первой буквой:
// «ВДНХ» и латиница остаются как есть.
const WORD_RE = /^[А-ЯЁа-яё][а-яё-]*$/;

function wordAccusative(word: string): string | null {
  if (word.length < 3 || !WORD_RE.test(word)) {
    return null;
  }
  for (const [from, to] of ACCUSATIVE_ENDINGS) {
    if (word.endsWith(from)) {
      return word.slice(0, -from.length) + to;
    }
  }
  return null;
}

/**
 * Название в винительном. Одно слово — склоняется. Из нескольких — первое
 * склоняется, только если за ним понятно что: после прилагательного на
 * -ая/-яя и после притяжательного — склоняется и второе («Олимпийскую
 * деревню», «Боеву Дачу»), перед определением в родительном — одно первое
 * («Рощу Победы»). Иначе название остаётся как есть.
 */
export function placeAccusative(name: string): string {
  const trimmed = name.trim();
  const words = trimmed.split(/\s+/);
  const first = wordAccusative(words[0] ?? "");
  if (first === null) {
    return trimmed;
  }
  if (words.length === 1) {
    return first;
  }
  const [head, second] = words;
  const possessive = POSSESSIVE_ENDINGS.some((ending) => head.endsWith(ending)) && /[ая]$/.test(second);
  if (/(ая|яя)$/.test(head) || possessive) {
    words[0] = first;
    words[1] = wordAccusative(second) ?? second;
    return words.join(" ");
  }
  if (GENITIVE_ENDINGS.some((ending) => second.endsWith(ending))) {
    words[0] = first;
    return words.join(" ");
  }
  return trimmed;
}

/** «бегу в Битцу», «бегу во Владимир»; без названия — «бегу в другую локацию». */
export function runToText(name: string | null | undefined): string {
  const place = name?.trim() ? placeAccusative(name) : "другую локацию";
  // «во» перед «в»/«ф» и согласной: «во Владимир», «во Фрязино».
  const preposition = /^[ВвФф][^аеёиоуыэюяАЕЁИОУЫЭЮЯ]/.test(place) ? "во" : "в";
  return `бегу ${preposition} ${place}`;
}
