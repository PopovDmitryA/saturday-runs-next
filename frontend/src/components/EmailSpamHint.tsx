import "./EmailSpamHint.css";

// Письмо с кодом почтовики нередко кладут в спам. Человек, не найдя письма,
// уходит совсем — поэтому подсказка висит на видном месте шага ввода кода, а
// не прячется в мелком тексте. Один компонент на вход и на привязку почты в
// настройках: письмо там одно и то же, и теряется оно одинаково.
//
// Адрес отправителя показываем строкой: по нему письмо ищут поиском в почте и
// его же добавляют в белый список.
export function EmailSpamHint({ sender }: { sender: string }) {
  return (
    <p className="email-spam-hint">
      <b>Письма нет?</b> Загляните в папку «Спам».
      {sender ? (
        <>
          {" "}
          Отправитель — <span className="email-spam-hint-sender">{sender}</span>.
        </>
      ) : null}{" "}
      Нашли в спаме — нажмите «Не спам», и следующие письма придут во «Входящие».
    </p>
  );
}
