/**
 * Общая блокировка прокрутки страницы под окнами («Меню», поиск, модалки).
 *
 * Раньше каждое окно само запоминало document.body.style.overflow при
 * открытии и возвращало запомненное при закрытии. Пока окна открываются и
 * закрываются строго по очереди, это работает. Но окна бывают вложены и
 * закрываются не в том порядке, в каком открылись: поиск, открытый поверх
 * выпадающего списка полосы, забирает его запись в истории
 * (nav/useOverlayHistory), и список закрывается уже ПОСЛЕ того, как поиск
 * запомнил «hidden». Список возвращал «», поиск при закрытии — свой «hidden»,
 * и страница переставала прокручиваться до перезагрузки (ревью перед пушем
 * 26.09.2026, NAV-1).
 *
 * Поэтому блокировка одна на всех и со счётчиком: прокрутка выключается с
 * первой блокировкой и возвращается, когда снята последняя, в каком бы
 * порядке их ни снимали.
 */

let holders = 0;
/** Что стояло в body до первой блокировки — это и вернём после последней. */
let savedOverflow = "";

/**
 * Запретить прокрутку страницы. Возвращает функцию снятия — её удобно
 * вернуть из useEffect как есть. Повторный вызов той же функции ничего не
 * делает: двойное снятие не должно разблокировать чужое окно.
 */
export function lockBodyScroll(): () => void {
  if (typeof document === "undefined") {
    return () => undefined;
  }
  if (holders === 0) {
    savedOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
  }
  holders += 1;
  let released = false;
  return () => {
    if (released) return;
    released = true;
    holders = Math.max(0, holders - 1);
    if (holders === 0) {
      document.body.style.overflow = savedOverflow;
    }
  };
}
