"""Имена очередей Celery.

Задачи 5 вёрст разведены на две группы, и у каждой свой воркер
(`worker-five-verst-fresh` и `worker-five-verst`):

* `five_verst_fresh` — свежесть: то, что показывает людям результаты сегодняшнего
  дня. Сюда попадает только `sync_latest_results` и точечная перечитка локации по
  команде админа. Очередь обязана оставаться короткой.
* `five_verst` — фон: сверка истории, обход недели, ротация локаций, реестр,
  клубы, доборка протоколов из профилей. Часы работы, никто не ждёт.

Разные контейнеры — единственный надёжный способ развести их по важности.
`queue_order_strategy: priority` обещает строгий порядок очередей из `-Q`, но
kombu хранит очереди воркера в set (`transport/redis.py`, `active_queues`), и
фактический порядок задаёт хеш строки — свой на каждый запуск процесса.
17.09.2026 воркер поднялся с порядком «сначала фон» и до 19.09 не забрал ни
одного `latest`: очередь свежести стояла нетронутой, а сайт показывал субботние
старты с одним участником. За 5verst.ru при этом можно не переживать: общий
Redis-лок на фетч берут все воркеры, к сайту идёт один запрос за раз.

Новая задача по умолчанию едет в ФОН. В `five_verst_fresh` попадает только то,
без чего сайт показывает людям вчерашний день.
"""

