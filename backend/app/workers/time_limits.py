"""Потолки времени выполнения задач Celery (CEL-01, 21.09.2026).

Зачем. Воркеры five_verst, five_verst_fresh, five_verst_user, s95, parkrun,
runpark работают с concurrency=1: задача, зависшая на сетевом сокете, держит
всю очередь, и ни одна из существующих страховок этого не снимает. `expires`
у beat отменяет только ещё НЕ начатую задачу; Redis-лок фетча отпустится по
TTL; брокерский visibility_timeout вернёт сообщение в очередь — но исполняющий
процесс так и останется занят зависшим сокетом. До этой правки лимит стоял
только у погоды и прогноза. Теперь конечный лимит есть у каждой задачи:
глобальный дефолт задан в `celery_app.conf`, здесь — именованные ступени
для явных переопределений в декораторах.

Как читать пару чисел. `soft_time_limit` — внутри задачи возбуждается
`SoftTimeLimitExceeded`, то есть отрабатывают `finally` (закрывается сессия
БД, прогон помечается провалом в sync_runs, снимается контекст
пользовательского синка). `time_limit` — спустя запас воркер убивает дочерний
процесс без разговоров. Запас — 5 минут, у пятиминутных задач — минута.
Обработчиков SoftTimeLimitExceeded нет намеренно: обрыв по лимиту должен
выглядеть как обычный провал прогона, а не как «штатное завершение».

Цифры согласованы с Дмитрием 21.09.2026 по журналу прогонов прода за 60 дней
(scheduled_run_logs). Для ориентира — avg / max в минутах по снимку журнала
18.07–08.09.2026:

    s95 API: обновлённые протоколы   25.0 / 148.3
    5v reconcile protocols           58.2 /  87.5  (до дробления на звенья 12.09.2026)
    s95 API: новые протоколы         14.1 /  77.5
    5v latest /results/latest/        3.3 /  54.0  (на проде — до 153 в тяжёлую субботу)
    s95 API: сверка протоколов       12.6 /  12.6
    5v clubs details                  9.0 /   9.8
    5v location rotation              1.6 /   8.8
    5v registry /events/              1.5 /   3.8
    s95 location descriptions         1.0 /   2.5
    5v clubs registry /clubs/         0.4 /   0.6
    runpark latest                    0.1 /   0.4

Лимит ставится заметно выше наблюдавшегося максимума: он ловит зависший
сокет, а не медленный день. Ужимать его «чтобы не мешал» смысла нет — обрыв
по лимиту виден в логе и в sync_runs, а вечно занятый воркер не виден нигде.
Обратное тоже верно: поднимать лимит «на всякий случай» — значит на столько же
дольше держать очередь под зависшей задачей.
"""

from __future__ import annotations

MINUTE = 60
HOUR = 60 * MINUTE


def _limits(soft_minutes: int, *, grace_minutes: int = 5) -> dict[str, int]:
    """Пара kwargs для декоратора: soft и hard = soft + запас на finally."""
    return {
        "soft_time_limit": soft_minutes * MINUTE,
        "time_limit": (soft_minutes + grace_minutes) * MINUTE,
    }


# Брокерский visibility_timeout (celery_app.conf.broker_transport_options).
# У задач 5 вёрст стоит acks_late=True, и их жёсткий лимит обязан быть НИЖЕ
# этого срока: иначе брокер вернёт в очередь ещё живую задачу, и она пойдёт
# вторым экземпляром. Самая долгая из них — latest, 185 минут; двух часов
# (прежнее значение) уже не хватало, отсюда четыре. Сторож — в
# tests/test_celery_beat_schedule.py.
BROKER_VISIBILITY_TIMEOUT = 4 * HOUR

# Глобальный дефолт для задачи без явного лимита (celery_app.conf). Это
# страховка на случай новой задачи, а не норма: у каждой существующей задачи
# лимит задан в декораторе, и тест требует конечного лимита у всех.
DEFAULT_SOFT_TIME_LIMIT = 60 * MINUTE
DEFAULT_TIME_LIMIT = 65 * MINUTE

# Постановка в очередь, один запрос к Redis или письмо: enqueue_*, гашение
# висяков sync_runs, наблюдатель приоритетных очередей, отправка письма.
LIMITS_SHORT = _limits(5, grace_minutes=1)

# Наблюдатель выгрузки протоколов 5 вёрст: поминутно в субботу, один запрос
# на локацию.
LIMITS_PROTOCOL_WATCH = _limits(15)

# Реестры, описания, сводки, пользовательские синки, суточные сводки, сверка
# состава событий S95: десятки запросов или несколько агрегатов. Максимум по
# журналу — 3.8 мин (реестр 5 вёрст), 12.6 — сверка S95 по дате (она ниже,
# в проходах API).
LIMITS_MEDIUM = _limits(20)

# Карточки клубов 5 вёрст: стабильно ~9 минут, лимит с тройным запасом.
LIMITS_CLUB_DETAILS = _limits(30)

# Ротация локаций 5 вёрст: несколько протоколов за проход, max 8.8 мин.
LIMITS_LOCATION_ROTATION = _limits(40)

# Перечитка одной локации по команде админа: вся история площадки, десятки
# протоколов через общий лок фетча.
LIMITS_ADMIN_LOCATION = _limits(60)

# Звенья цепочек фона 5 вёрст: сверка истории (батч
# five_verst_reconcile_batch_limit протоколов) и обход недели. До дробления
# 12.09.2026 сверка шла до 87 минут одним куском — лимит звена оставлен с тем
# же запасом, чтобы ловить именно зависание.
LIMITS_CHAIN = _limits(110)

# Обход /results/latest/ по всем локациям 5 вёрст. На проде тяжёлая суббота
# давала 153 минуты (много новых протоколов через один лок фетча), поэтому
# три часа. Задача с acks_late: см. BROKER_VISIBILITY_TIMEOUT.
LIMITS_LATEST = _limits(180)

# Проходы JSON-API S95 по всем локациям. Они НЕ возобновляемые: прерванный
# проход теряет остаток до следующего слота расписания, поэтому лимит
# поставлен выше наблюдавшегося максимума (148 мин), а не «покороче, чтобы не
# мешал». Подрезать его можно, когда проход научится продолжаться с места
# остановки.
LIMITS_S95_PASS = _limits(180)

# Разовый ручной проход по всей истории S95 (api_full_backfill).
LIMITS_BACKFILL = _limits(360)

# Прогревы кэша. Сети нет, только БД: лимит здесь — от зависшего запроса к
# базе. Главная и дашборды — минуты, каталог локаций — десятки агрегатов,
# рейтинги — самый долгий (полтора часа с запасом).
LIMITS_WARM_DASHBOARDS = _limits(40)
LIMITS_WARM_LOCATIONS = _limits(60)
LIMITS_WARM_LEADERBOARDS = _limits(90)

# Рендер OG-картинок: сотни страниц через Playwright по нескольку секунд.
LIMITS_OG_RENDER = _limits(120)
