"""Неделя субботнего старта: к какой субботе относится дата активности.

Общее правило для всего сайта: календарь суббот в кабинете, серии дашборда,
вехи «Моей истории», челлендж «Серийный бегун» и цели по субботам считают не
буквальные субботы, а НЕДЕЛИ — иначе перенос старта или внеплановый будний
старт рвут серию на ровном месте.

Неделя — пн–вс: воскресенье относится к субботе, которая только что прошла, а
не к следующей. Ровно так выглядит перенос: 01.11.2025 была рабочей субботой,
и 122 локации 5 вёрст побежали в воскресенье 02.11 (репорт Дмитрия Евлаша
16.09.2026). Заодно воскресные старты RunPark складываются в одну клетку с
субботой тех же выходных.

Живёт отдельным модулем, потому что правило одно на несколько сервисов: пока
у дашборда и у челленджей были свои копии, они успели разъехаться — дашборд
считал по неделям, а «Серийный бегун» по буквальным субботам.
"""

from __future__ import annotations

from datetime import date, timedelta


def week_saturday(value: date) -> date:
    """Суббота недели (пн–вс), в которую попал старт."""
    return value + timedelta(days=5 - value.weekday())


def saturday_weeks(activity_dates: set[date]) -> set[date]:
    """Недели-с-активностью, каждая — своей субботой.

    Два старта в одну неделю (та же суббота двумя протоколами, суббота плюс
    будний старт) схлопываются в одну запись и серию не удлиняют.
    """
    return {week_saturday(value) for value in activity_dates}


def max_saturday_streak(activity_dates: set[date]) -> int:
    """Самая длинная серия недель подряд среди дат активности."""
    best = 0
    current = 0
    previous: date | None = None
    for value in sorted(saturday_weeks(activity_dates)):
        current = current + 1 if previous is not None and value - previous == timedelta(days=7) else 1
        best = max(best, current)
        previous = value
    return best
