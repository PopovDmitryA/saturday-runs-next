"""Реестр особых наград — тех, что выдаются руками, а не считаются из протоколов.

Челленджи и клубы (achievements_service) вычисляются на лету из результатов, и
забрать их нельзя: они всегда правда о протоколах. Особая награда — решение
админа о конкретном человеке («Тысячный участник»), поэтому она хранится
строкой в `user_awards` и выдаётся в админке (/admin/users → «Награды»).

Виды живут в коде, как и виды уведомлений: новая награда — новая запись здесь,
без миграции. Название, значок и текст общие для всех обладателей, у выдачи
своя только дата (`awarded_on` — когда событие случилось, а не когда админ
нажал кнопку) и заметка для админа.

`single_holder=True` — награда существует в одном экземпляре на весь сайт:
вторая выдача другому человеку отклоняется, пока первую не отзовут.

Значок у всех особых наград один по форме — почтовая марка с перфорацией и
гашением (выбор Дмитрия 21.10.2026 из десяти вариантов): среди круглых
золотых медалей она сразу читается как другой предмет, а награды становятся
серией марок. На марке:
  * `emblem` — номер выпуска крупно под «№» (число юбилейной награды: «1000»,
    потом «10 000»); если его нет — `icon` (символ тематической награды);
  * `caption` — подпись мелкими прописными внизу («УЧАСТНИК»);
  * `tone` — цвет поля марки: carmine, ultramarine, emerald (палитра — в
    AwardStamp на фронте); у каждой награды свой.
`icon` нужен и сам по себе: им награда подписана в админке и в текстовых
каналах, где марку не нарисовать.

Показ — первыми в витрине «Мои достижения», такой же клеткой, как медали, но
со значком-маркой; описание — в подсказке (решения Дмитрия 20.10.2026:
без отдельного раздела и без отдельной плашки). Уровни сложности и фильтр
систем витрины на них не действуют.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class AwardKind:
    code: str
    title: str
    icon: str
    description: str
    single_holder: bool = False
    # Номер на марке вместо icon — до 6 символов («1000», «10 000»)
    emblem: str | None = None
    # Подпись внизу марки прописными, до 10 символов
    caption: str | None = None
    # Цвет поля марки: carmine | ultramarine | emerald
    tone: str = "carmine"


AWARD_KINDS: tuple[AwardKind, ...] = (
    AwardKind(
        code="site_user_1000",
        title="Тысячный участник",
        icon="🎖️",
        description="Тысячным привязал профиль к run5k.run.",
        single_holder=True,
        emblem="1000",
        caption="УЧАСТНИК",
        tone="carmine",
    ),
)

AWARD_BY_CODE: dict[str, AwardKind] = {kind.code: kind for kind in AWARD_KINDS}
