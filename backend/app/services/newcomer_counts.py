"""Как считаются новые лица старта: новички системы и те, кто здесь впервые.

Два флага в run_results отвечают на разные вопросы:

* `is_first_run` — человек впервые вышел на старт этой системы (дебют);
* `is_first_run_at_location` — человек впервые вышел на старт этой площадки.

У новичка верны оба: его первый старт в системе — заодно и первый на этой
площадке. Так их проставляет `personal_record_service.recompute_first_run_flags`
(parkrun, RunPark, S95); у 5 вёрст флаги приходят с бейджей протокола, и там
они взаимоисключающие. Поэтому «новички + впервые здесь» — не сумма, а
двойной счёт для всех систем, кроме 5 вёрст.

Разделение, которое имеет смысл в обеих ролях (и им уже пользуются отчёты
организатора): новички системы — отдельно, «впервые здесь» — те, кто на
5 вёрст/parkrun уже бегал, а сюда пришёл впервые. Первое число говорит,
насколько площадка вовлекает новых людей, второе — насколько хорошо она
зазывает уже бегающих.

Безымянные строки протокола («НЕИЗВЕСТНЫЙ», «Неизвестный бегун») не считаются
ни новичками, ни «впервые здесь»: под каждую такую строку заводится своя
одноразовая личность, и по хронологии она всегда «впервые» — см.
app/participant_identity.py (там же имена-заглушки). До 18.09.2026 так набегало 44% «новичков» RunPark
и 28% S95.

Не путать с ГОСТЯМИ (`location_guests_service`): гость — тот, чей дом другая
площадка, и приезжать он может не в первый раз. «Впервые здесь» — подмножество
гостей, а не синоним.
"""

from __future__ import annotations

from sqlalchemy import case, func

from app.models import RunResult


def debutants_sum():
    """Новички системы: первый старт в 5 вёрст / parkrun / RunPark / S95.

    Имя функции историческое — на сайте эта метрика называется «Новички»
    (переименование 14.09.2026), поле API осталось `debutants`.
    """
    return func.sum(case((RunResult.is_first_run.is_(True), 1), else_=0))


def first_at_location_sum():
    """Впервые на этой площадке, но в системе бегали и раньше."""
    return func.sum(
        case(
            (
                RunResult.is_first_run_at_location.is_(True)
                & RunResult.is_first_run.isnot(True),
                1,
            ),
            else_=0,
        )
    )
