"""Человекочитаемые названия систем — единственный источник для бэкенда.

В platforms.name лежат исторические варианты («с95», «Runpark»), поэтому в
тексты для людей идёт этот словарь, а не поле из БД.

До 21.09.2026 (аудит, DUP-01) свои копии словаря держали ещё три модуля
(уведомления об отменах, тексты ошибок синка, SEO), и они успели разъехаться:
у S95 в одних местах стояла латинская «S», в других — кириллическая «С».
Каноническое написание — кириллическое «С95»: так система подписана во
фронте (platformCodeLabel в frontend/src/lib/format.ts, pageMeta.ts), и
тест test_seo_service сверяет этот словарь с pageMeta.ts буква в букву.
Латинское «S95» остаётся только в коде и URL (s95.ru), не в текстах.
"""

from __future__ import annotations

# Порядок — как на портале: действующие системы по величине, затем архив
# parkrun. Словарь ниже перечислен в том же порядке, чтобы обход по нему давал
# ту же последовательность.
PLATFORM_ORDER: tuple[str, ...] = ("five_verst", "s95", "runpark", "parkrun")

PLATFORM_TITLES: dict[str, str] = {
    "five_verst": "5 вёрст",
    "s95": "С95",
    "runpark": "RunPark",
    "parkrun": "parkrun",
}


def platform_title(code: str | None) -> str:
    """Название системы по коду; незнакомый код возвращается как есть.

    Возврат кода вместо пустой строки — сознательный: в админских текстах и
    логах лучше увидеть «other», чем пустое место.
    """
    if not code:
        return ""
    return PLATFORM_TITLES.get(code, code)
