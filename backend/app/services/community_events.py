"""Старты сообществ 5 вёрст — единственная точка правды про их исключение.

Раздел `/starti-soobshchestv/` — разовые старты («Зелёные 5 км», «День
физкультурника. Тула»). Финиши с них 5 вёрст засчитывает в личный счётчик
человека, поэтому собирать их надо: без них наши числа расходятся с источником
ровно на единицу у каждого, кто там бежал.

Но площадкой такой старт не является: ни расписания, ни координат, ни второго
старта. Поэтому он не должен попадать туда, где перечисляются ПЛОЩАДКИ:
каталог, карта, туризм («сколько уникальных локаций посетил»), рейтинги по
локациям и регионам, рекорды трасс, «Первопроходцы», единый протокол недели,
sitemap.

Правило простое: считаем в личных итогах человека — не считаем в витринах о
площадках. Все проверки идут через этот модуль, чтобы условие не расползлось
по два десятка запросов и не разъехалось при следующей правке.
"""

from __future__ import annotations

from sqlalchemy.orm import Query

from app.models import Location


def is_community_event(location: Location | None) -> bool:
    """Разовый старт сообщества, а не площадка."""
    return bool(location is not None and location.is_community_event)


def exclude_community_events(query: Query) -> Query:
    """Отсечь старты сообществ из запроса, который перечисляет площадки.

    Ждёт, что `Location` уже участвует в запросе (join или select).
    """
    return query.filter(Location.is_community_event.is_(False))
