from __future__ import annotations


def plural_form(count: int, forms: tuple[str, str, str]) -> str:
    """Форма для числа: forms = (одна, две–четыре, пять и больше)."""
    n = abs(count)
    if 11 <= n % 100 <= 14:
        return forms[2]
    last = n % 10
    if last == 1:
        return forms[0]
    if last in (2, 3, 4):
        return forms[1]
    return forms[2]


