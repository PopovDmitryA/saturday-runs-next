"""Названия регионов России: ключ для группировки и полное имя для витрины.

В БД регион лежит в сокращённой форме — «Московская», «Краснодарский»,
«Ханты-Мансийский автономный округ — Югра»: так его пишет обратный геокод после
normalize_region. Для группировки этого достаточно, а для таблицы — нет:
«Московская» в колонке «Регион» читается как обрезанное слово.

Ключ считается ровно теми же правилами, что и regionKey на фронте
(frontend/src/lib/regionMatch.ts) — карта-хороплет матчит регионы БД с GeoJSON
по нему же, и два разных правила разъехались бы на первой же «Удмуртской».

Полные названия взяты из того же GeoJSON, которым рисуется карта регионов
(frontend/public/russia-regions.geojson) — файл сгенерирован из него.
Подставляем их только там, где полное имя ДОПОЛНЯЕТ сокращённое
(«Московская» → «Московская область»). Если написания расходятся по существу
(«Республика Алтай» против «Алтай», «Северная Осетия — Алания» против дефисной
формы), остаётся значение из БД: оно полнее и привычнее, а витрина не место
для переименований. Регионы, которых в этом GeoJSON нет, показываются как есть.
"""

from __future__ import annotations

import re

# Слова-типы региона: в ключе их нет, поэтому «Московская область» и
# «Московская» — один и тот же регион.
_TYPE_WORDS = ("автономный округ", "автономная область", "область", "край", "республика")

# Регионы, чьи прилагательные формы не совпадают между БД и GeoJSON.
_KEY_ALIASES = {
    "удмуртская": "удмуртия",
    "чеченская": "чечня",
    "чувашская": "чувашия",
}


def region_key(raw: str | None) -> str:
    """Ключ группировки региона. Пустая строка — региона нет."""
    if not raw:
        return ""
    value = raw.lower().strip()
    value = re.sub(r"[—–]", "-", value)
    for word in _TYPE_WORDS:
        value = value.replace(word, " ")
    value = re.sub(r"[^\w\s()-]", " ", value, flags=re.UNICODE)
    value = re.sub(r"\s+", " ", value).strip()
    return _KEY_ALIASES.get(value, value)


def region_display_name(raw: str | None) -> str:
    """Как регион называется в витрине: с «областью»/«краем», если это дополнение."""
    if not raw:
        return ""
    value = raw.strip()
    full = RU_REGION_FULL_NAMES.get(region_key(value))
    if full and full.startswith(value):
        return full
    return value


