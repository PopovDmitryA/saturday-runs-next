def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--apply", action="store_true", help="Записать (без флага — только показать план)")
    args = parser.parse_args()

    session_factory = get_session_factory()
    with session_factory() as db:
        existing = set(db.execute(select(SiteRelease.version)).scalars().all())
        created = 0
        for entry in HISTORY:
            marker = "= есть" if entry["version"] in existing else "+ новый"
            print(f"{marker}  {entry['version']:<12} {entry['released_at']}  {entry['title']}")
            if entry["version"] in existing or not args.apply:
                continue
            create_release(
                db,
                version=entry["version"],
                title=entry["title"],
                body=entry["body"],
                released_at=entry["released_at"],
                is_published=False,
            )
            created += 1

    if args.apply:
        print(f"Создано записей: {created} (все скрыты — открыть в /admin/releases)")
    else:
        print("Прогон без записи. Запись: --apply")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
